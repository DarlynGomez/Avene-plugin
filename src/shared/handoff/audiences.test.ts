import { describe, expect, it } from "vitest";

import { buildAudienceDoc } from "./audiences";
import { CLIENT_LINE, HIGHER_UP_LINE, NOT_COVERED_LINE } from "./fixedLines";
import { DECISION, finding, ignoredFinding, input } from "./handoffFixtures";
import { startsWithLabel } from "./labels";
import { renderPmSummary } from "./pmSummary";
import { exemptLines, renderAudience } from "./render";
import type { Audience, HandoffInput } from "./types";

const HEX = /#[0-9A-Fa-f]{3,8}\b/;

function rich(): HandoffInput {
  return input({
    fileUrl: "https://www.figma.com/design/KEY/Checkout",
    findings: [
      finding({ link: "https://www.figma.com/design/KEY/Checkout?node-id=1-1" }),
      ignoredFinding()
    ],
    decisions: { [DECISION.signature]: DECISION },
    changes: [
      {
        nodeName: "Title",
        beforeHex: "#AAAAAA",
        beforeRatio: 2.3,
        afterHex: "#595959",
        afterRatio: 7,
        instanceCount: 2
      }
    ],
    questions: [
      { text: "Focus after Apply?", owner: "Dev" },
      { text: "Who signs off the banner?", owner: "PM" }
    ]
  });
}

function render(audience: Audience): string {
  return renderAudience(buildAudienceDoc(rich(), audience));
}

describe("audience versions", () => {
  it("carry hex values in the developer version only", () => {
    expect(render("developer")).toMatch(HEX);
    for (const audience of ["pm", "higherUp", "client"] as const) {
      expect(render(audience), audience).not.toMatch(HEX);
    }
  });

  it("use plain-word labels for everyone but developers", () => {
    for (const audience of ["pm", "higherUp", "client"] as const) {
      const text = render(audience);
      expect(text, audience).not.toMatch(/^(Detected|Decision|Needs check)/m);
      expect(text, audience).toContain("Measured:");
    }
    expect(render("developer")).toMatch(/^Detected:/m);
  });

  it("puts the client line in the client version exactly once and nowhere else", () => {
    const count = (text: string) => text.split(CLIENT_LINE).length - 1;
    expect(count(render("client"))).toBe(1);
    for (const audience of ["developer", "pm", "higherUp"] as const) {
      expect(count(render(audience)), audience).toBe(0);
    }
    expect(render("higherUp").split(HIGHER_UP_LINE).length - 1).toBe(1);
  });

  it("ends every version with the Not covered line in the reader's labels", () => {
    expect(render("developer").endsWith(NOT_COVERED_LINE)).toBe(true);
    expect(
      render("client").endsWith(NOT_COVERED_LINE.replace("Needs check", "Still to check"))
    ).toBe(true);
  });

  it("keeps layer names out of higher-up and client versions and the internal status out of the client", () => {
    for (const audience of ["higherUp", "client"] as const) {
      const text = render(audience);
      expect(text).not.toContain("Promo banner");
      expect(text).not.toContain("Helper text");
    }
    expect(render("client")).not.toContain("sign-off");
    expect(render("pm")).toContain("Promo banner");
    expect(render("pm")).toContain("Status: Needs sign-off");
  });

  it("selects questions by owner and keeps changes to developers", () => {
    expect(render("developer")).toContain("(owner: Dev): Focus after Apply?");
    expect(render("developer")).not.toContain("Who signs off");
    expect(render("pm")).toContain("(owner: PM): Who signs off the banner?");
    expect(render("client")).not.toContain("Focus after");
    expect(render("developer")).toContain("changed from");
    expect(render("pm")).not.toContain("changed from");
  });

  it("keeps the advisory section hidden for every version today", () => {
    for (const audience of ["developer", "pm", "higherUp", "client"] as const) {
      expect(buildAudienceDoc(rich(), audience).sections.some((s) => s.id === "advisory")).toBe(
        false
      );
    }
  });

  it("shares one findings hash across versions", () => {
    const hashes = (["developer", "pm", "higherUp", "client"] as const).map(
      (a) => buildAudienceDoc(rich(), a).hash
    );
    expect(new Set(hashes).size).toBe(1);
  });
});

describe("exempt lines", () => {
  const NOTICES: Record<Audience, string[]> = {
    developer: [],
    pm: [],
    higherUp: [
      "Whether these items affect a conformance claim depends on what the organization has claimed. Avene makes no conformance claim."
    ],
    client: ["Draft for the designer to send. Not a conformance statement."]
  };
  const HEADER = [
    /^Accessibility handoff: .+/,
    /^Generated by Avene \S+, findings hash [0-9a-f]{8}$/,
    /^Reviewed by .+, \d{4}-\d{2}-\d{2}$/,
    /^Checks: text contrast \(WCAG 1\.4\.3\), design file only$/,
    /^Links: off, no file address has been pasted$/
  ];
  const PLAIN = /^(Measured|Decided|Still to check)(?: \(owner: (?:Dev|PM|Design)\))?: /;

  it.each(["developer", "pm", "higherUp", "client"] as const)(
    "are only the header block and the fixed notices in the %s version",
    (audience) => {
      const doc = buildAudienceDoc(
        input({ ...rich(), fileUrl: undefined, reviewer: { name: "Sam", date: "2026-10-27" } }),
        audience
      );
      expect(doc.notices).toEqual(NOTICES[audience]);
      expect(exemptLines(doc)).toEqual([...doc.header, ...doc.notices]);
      for (const line of doc.header) {
        expect(
          HEADER.some((pattern) => pattern.test(line)),
          line
        ).toBe(true);
      }
      const allowed = [...exemptLines(doc), ...doc.sections.flatMap((s) => ["", `## ${s.title}`])];
      const rendered = renderAudience(doc).split("\n");
      const unlabeled = rendered.filter((line) =>
        audience === "developer" ? !startsWithLabel(line) : !PLAIN.test(line)
      );
      expect([...unlabeled].sort()).toEqual([...allowed].sort());
    }
  );
});

describe("designer text hits", () => {
  const withReason = (reason: string, audience: Audience) => {
    const decision = { ...DECISION, reason };
    const source = input({
      findings: [ignoredFinding()],
      decisions: { [DECISION.signature]: decision }
    });
    return { source, doc: buildAudienceDoc(source, audience) };
  };

  it("reports a hex and a digit run in a reason and leaves the text as written", () => {
    for (const audience of ["pm", "higherUp", "client"] as const) {
      const { doc } = withReason("Brand #FF7A1A for the 2026 campaign", audience);
      expect(doc.warnings, audience).toEqual([
        { item: DECISION.signature, field: "reason", kind: "hex", match: "#FF7A1A" },
        { item: DECISION.signature, field: "reason", kind: "digits", match: "2026" }
      ]);
      expect(renderAudience(doc)).toContain("Brand #FF7A1A for the 2026 campaign");
    }
  });

  it("checks mitigation, revisit and PM questions, and skips developers", () => {
    const { source } = withReason("plain", "pm");
    const richer = {
      ...source,
      meta: {
        [DECISION.signature]: {
          signOff: "needs" as const,
          leaveOut: false,
          mitigation: "Use #333",
          revisitTrigger: "Q4"
        }
      },
      questions: [
        { text: "Is 3:1 enough?", owner: "PM" as const },
        { text: "Dev only #123", owner: "Dev" as const }
      ]
    };
    const pm = buildAudienceDoc(richer, "pm").warnings.map((w) => `${w.field}:${w.match}`);
    expect(pm).toEqual(["mitigation:#333", "revisitTrigger:4", "text:3", "text:1"]);
    expect(buildAudienceDoc(richer, "developer").warnings).toEqual([]);
  });

  it("has nothing to report for clean text, and higher-up sees only items waiting", () => {
    expect(withReason("Brand color", "client").doc.warnings).toEqual([]);
    const signed = {
      ...withReason("Code #FFF", "higherUp").source,
      meta: { [DECISION.signature]: { signOff: "signed" as const, leaveOut: false } }
    };
    expect(buildAudienceDoc(signed, "higherUp").warnings).toEqual([]);
    expect(buildAudienceDoc(signed, "pm").warnings).toHaveLength(1);
  });
});

describe("renderPmSummary", () => {
  it("is three lines with plain labels and no hex", () => {
    const lines = renderPmSummary(rich());
    expect(lines).toHaveLength(3);
    expect(lines[0]).toBe("Measured: Payment: 1 text contrast item for developers (1 layer).");
    expect(lines[1]).toBe(
      "Still to check (owner: PM): 1 item left as-is, waiting for sign-off. Highest: 2.9:1 against 4.5:1."
    );
    expect(lines[2]).toMatch(/^Still to check: Keyboard, screen reader output/);
    expect(lines.join("\n")).not.toMatch(HEX);
  });

  it("says no sign-off is waiting and nothing needs action", () => {
    const lines = renderPmSummary(input());
    expect(lines[0]).toBe("Measured: No text contrast items need developer action in Payment.");
    expect(lines[1]).toBe("Still to check (owner: PM): No sign-off waiting.");
  });
});
