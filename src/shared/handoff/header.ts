import { CHECKS_LINE } from "./fixedLines";
import { dateOnly } from "./text";
import type { HandoffInput } from "./types";

/** Metadata lines, no hash yet and no reviewer line until the review gate is passed */
export function buildHeader(input: HandoffInput): string[] {
  const screens = input.screens.map((screen) => screen.name).join(", ");
  const lines = [
    `Accessibility handoff: ${input.fileName}, ${screens}`,
    `Generated by Avene ${input.generatedAt}`
  ];
  if (input.reviewer) {
    lines.push(`Reviewed by ${input.reviewer.name}, ${dateOnly(input.reviewer.date)}`);
  }
  lines.push(CHECKS_LINE);
  return lines;
}
